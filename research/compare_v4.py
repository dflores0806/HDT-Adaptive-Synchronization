#!/usr/bin/env python3
"""IoTJ V4: descriptive, variant-aware and quality-flagged replication audit.

Accepts a campaign ZIP generated by package_campaign_v4.py, or a campaign
folder. Requires plan.json to identify *separate* A1 configurations. Every
run is retained in the report; quality flags are diagnostics, not an automatic
post-hoc choice of the best policy. Python standard library only.
"""
from __future__ import annotations
import argparse
import csv
import io
import json
import statistics
import zipfile
from collections import defaultdict
from pathlib import Path


def _load_source(path):
    path=Path(path)
    if path.is_file() and path.suffix.lower()=='.zip':
        with zipfile.ZipFile(path) as archive:
            files={p:archive.read(p) for p in archive.namelist() if p.endswith(('.json','.csv'))}
    elif path.is_dir():
        files={p.relative_to(path).as_posix():p.read_bytes() for p in path.rglob('*') if p.is_file() and p.suffix.lower() in ('.json','.csv')}
    else:
        raise ValueError('Expected campaign .zip or extracted directory')
    candidates=[p for p in files if p.endswith('plan.json')]
    if len(candidates)!=1:
        raise ValueError(f'Exactly one plan.json required, found {len(candidates)}')
    prefix=candidates[0][:-len('plan.json')]
    plan=json.loads(files[candidates[0]])
    return files,prefix,plan


def _value(d,*names,default=None):
    for key in names:
        if not isinstance(d,dict) or key not in d:
            return default
        d=d[key]
    return d


def examine_campaign(path, min_coverage=.95, min_decision_ratio=.95):
    if not (0<min_coverage<=1 and 0<min_decision_ratio<=1):
        raise ValueError('thresholds must be in (0,1]')
    files,prefix,plan=_load_source(path)
    run_rows=[]
    for task in plan['tasks']:
        run_id=task['run_id']
        base=prefix+'runs/'+run_id+'/'
        summary_key=base+'summary_v2.json'
        meta_key=base+'metadata.json'
        config=task['config']
        variant=config.get('variant',config['mode'])
        policy_env=config.get('policy_env',{})
        row={'run_id':run_id,'mode':config['mode'],'variant':variant,
             'n':config['n'],'repeat':config['repeat'],
             'fixed_interval_s':config.get('fixed_interval'),
             'aoi_threshold_s':config.get('aoi_threshold'),
             'policy_env':json.dumps(policy_env,sort_keys=True),
             'task_status':task.get('status','unknown'),'run_complete':False,
             'quality_ok':False,'quality_issues':''}
        if summary_key not in files or meta_key not in files:
            row['quality_issues']='missing_summary_or_metadata'
            run_rows.append(row)
            continue
        s=json.loads(files[summary_key]); m=json.loads(files[meta_key])
        comm=s['communication']; cn=s['controller']; ref=s['reference_fidelity']
        dense=s.get('dense_synthetic_oracle_fidelity') or {}
        cadence=s.get('cadence_v9') or {}
        duration=(__import__('datetime').datetime.fromisoformat(m['end_utc'])-__import__('datetime').datetime.fromisoformat(m['start_utc'])).total_seconds() if m.get('start_utc') and m.get('end_utc') else float(plan.get('measurement_s',0))
        horizons=cn.get('decision_horizons_s') or [2.]
        horizon=float(horizons[0])
        decision_ratio=float(cn.get('decision_count',0))/(duration/horizon) if duration>0 else 0.
        coverage=ref.get('reference_cadence_coverage_fraction')
        if coverage is None:
            coverage=0.
        quality=[]
        if task.get('status')!='complete' or not m.get('run_complete'):
            quality.append('incomplete_execution')
        if float(coverage)<min_coverage:
            quality.append('reference_cadence_below_threshold')
        if decision_ratio<min_decision_ratio:
            quality.append('decision_cadence_below_threshold')
        if dense.get('nmae') is None:
            quality.append('missing_dense_oracle')
        if dense.get('unmatched_reference_fraction',1.)>0:
            quality.append('unmatched_dense_state')
        if comm.get('state_rejected_or_duplicate',0)>0:
            quality.append('rejected_or_duplicate_updates_present')
        # Predicted SLO feasibility is *not* a measurement-quality failure,
        # but is retained separately so such baselines are not misrepresented.
        row.update({'run_complete':bool(m.get('run_complete')),
                    'measurement_s':duration,'decision_count':cn.get('decision_count'),
                    'expected_decisions':duration/horizon if horizon else None,
                    'decision_cadence_ratio':decision_ratio,
                    'reference_cadence_coverage':float(coverage),
                    'operational_http_bytes':comm['operational_http_payload_bytes'],
                    'state_http_bytes':comm['operational_state_bytes'],
                    'heartbeat_http_bytes':comm['monitoring_heartbeat_bytes'],
                    'evaluation_reference_bytes':comm['evaluation_reference_bytes'],
                    'total_recorded_http_bytes':comm['total_recorded_http_payload_bytes'],
                    'updates_received':comm['state_attempts_observed_by_server'],
                    'nmae_ref_2s':ref['nmae'],
                    'nmae_dense_0p5s':dense['nmae'],
                    'dense_aoi_p95_s':dense['aoi_p95_s'],
                    'dense_unmatched_fraction':dense.get('unmatched_reference_fraction'),
                    'feasible_fraction':cn['feasible_fraction'],
                    'coverage_violations':cn.get('violation_counts',{}).get('subsystem_coverage',0),
                    'decision_runtime_p95_ms':cn.get('policy_runtime_p95_ms'),
                    'quality_ok':not quality,'quality_issues':';'.join(quality),
                    'timing_log_status':cadence.get('timing_log_status','not_collected'),
                    'agent_schedule_lag_p95_ms':(cadence.get('agent',{}).get('schedule_lag_ms') or {}).get('p95'),
                    'agent_slots_skipped':cadence.get('agent',{}).get('ticks_skipped'),
                    'agent_reference_http_failures':cadence.get('agent',{}).get('reference_http_failures'),
                    'policy_schedule_lag_p95_ms':(cadence.get('policy',{}).get('schedule_lag_ms') or {}).get('p95'),
                    'policy_slots_skipped':cadence.get('policy',{}).get('ticks_skipped')})
        run_rows.append(row)

    groups=defaultdict(list)
    for row in run_rows:
        key=(row['n'],row['mode'],row['variant'],row['fixed_interval_s'],row['aoi_threshold_s'],row['policy_env'])
        groups[key].append(row)
    group_rows=[]
    cols=('operational_http_bytes','state_http_bytes','heartbeat_http_bytes',
          'evaluation_reference_bytes','updates_received','nmae_ref_2s',
          'nmae_dense_0p5s','dense_aoi_p95_s','feasible_fraction')
    for key, recs in sorted(groups.items(),key=lambda kv:(kv[0][1],kv[0][2])):
        valid=[r for r in recs if r['run_complete'] and r.get('nmae_dense_0p5s') is not None]
        passing=[r for r in valid if r['quality_ok']]
        o={'n':key[0],'mode':key[1],'variant':key[2],
           'fixed_interval_s':key[3],'aoi_threshold_s':key[4],
           'policy_env':key[5],'runs_total':len(recs),'runs_complete':len(valid),
           'runs_quality_ok':len(passing),
           'quality_status':'pilot_only' if len(passing)<3 else 'three_quality_checked_runs',
           'warning':'Exploratory descriptive statistics; distinct source scenarios and independent deployment replication required'}
        for col in cols:
            values=[float(r[col]) for r in valid if r.get(col) is not None]
            good=[float(r[col]) for r in passing if r.get(col) is not None]
            o[col+'_mean']=statistics.mean(values) if values else None
            o[col+'_sd']=statistics.stdev(values) if len(values)>1 else None
            o[col+'_quality_mean']=statistics.mean(good) if good else None
        group_rows.append(o)
    return {'campaign_id':plan['campaign_id'],'profile':plan['profile'],
            'quality_rule':{'reference_cadence_min':min_coverage,
                            'decision_cadence_min':min_decision_ratio,
                            'source_coverage':'reference stream approximately every 2 seconds; not wire-level offered traffic',
                            'scope':'diagnostic flags only, not a pre-registered exclusion for an inferential test'},
            'summary':{'planned':len(plan['tasks']),'complete':sum(r['run_complete'] for r in run_rows),
                       'quality_ok':sum(r['quality_ok'] for r in run_rows),
                       'n_variants':len(groups)},
            'runs':run_rows,'groups':group_rows}


def _write_csv(path,rows):
    if not rows:return
    keys=list(dict.fromkeys(k for row in rows for k in row))
    with open(path,'w',newline='',encoding='utf-8-sig') as f:
        writer=csv.DictWriter(f,fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('campaign',type=Path)
    p.add_argument('--out',type=Path,default=Path('iotj_replication_audit'))
    p.add_argument('--min-reference-coverage',type=float,default=.95)
    p.add_argument('--min-decision-coverage',type=float,default=.95)
    a=p.parse_args()
    result=examine_campaign(a.campaign,a.min_reference_coverage,a.min_decision_coverage)
    a.out.mkdir(parents=True,exist_ok=True)
    (a.out/'audit.json').write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding='utf-8')
    _write_csv(a.out/'runs.csv',result['runs'])
    _write_csv(a.out/'groups.csv',result['groups'])
    print(json.dumps(result['summary'],indent=2))
    for row in result['runs']:
        if not row['quality_ok']:
            print('QUALITY WARNING',row['variant'],'r',row['repeat'],':',row['quality_issues'])

if __name__=='__main__':main()
